all_pages = andersen_tales + tales_5_to_9 + tales_10_to_15
output_file = os.path.join(os.path.dirname(__file__), "book_10_data.py")

with open(output_file, "w", encoding="utf-8") as f:
    f.write("# -*- coding: utf-8 -*-\n")
    f.write('"""\n')
    f.write("Book 10: Hans Christian Andersen: Tales of Wonder (Hans Christian Andersen Masalları)\n")
