import sys

all_pages = (oz_chapters_1_to_5[:5] + 
             oz_chapters_6_to_10[:5] + 
             oz_chapters_11_to_15[:5])

output_file = os.path.join(os.path.dirname(__file__), "book_13_data.py")

with open(output_file, "w", encoding="utf-8") as f:
    f.write("# -*- coding: utf-8 -*-\n")
    f.write('"""\n')
    f.write("Book 13: The Wonderful Wizard of Oz: Journey to the Emerald City (L. Frank Baum)\n")
    f.write("Level 1 Graded Reader — 15 Pages x 20 Sentences = 300 Sentences.\n")
    f.write('"""\n\n')
    f.write('BOOK_TITLE = "The Wonderful Wizard of Oz (15 Sayfa / 300 Cümle / Graded Reader)"\n')
    f.write('AUTHOR = "L. Frank Baum"\n\n')
    f.write("PAGES_DATA = [\n")
    
    current_sentence_id = 1
    for page in all_pages:
        f.write("    {\n")
        f.write(f'        "page_no": {page["page_no"]},\n')
        f.write(f'        "title": "{page["title"]}",\n')
        f.write(f'        "tr_title": "{page["tr_title"]}",\n')
        f.write('        "sentences": [\n')
        for s_idx, s in enumerate(page["sentences"]):
            if len(s) < 3:
                print(f"Error: page {page['page_no']} ({page['title']}) sentence {s_idx} has only {len(s)} elements: {s}")
                sys.exit(1)
            text = s[0].replace('"', '\\"')
            tr = s[1].replace('"', '\\"')
            notes = s[2].replace('"', '\\"')
            f.write("            {\n")
            f.write(f'                "id": {current_sentence_id},\n')
            f.write(f'                "text": "{text}",\n')
            f.write(f'                "translation": "{tr}",\n')
            f.write(f'                "notes": "{notes}"\n')
            f.write("            },\n")
            current_sentence_id += 1
        f.write("        ],\n")
        f.write('        "vocab_focus": [\n')
        for v in page["vocab_focus"]:
            v_en = v[0].replace('"', '\\"')
            v_tr = v[1].replace('"', '\\"')
            f.write(f'            ("{v_en}", "{v_tr}"),\n')
        f.write("        ]\n")
        f.write("    },\n")
    f.write("]\n")

